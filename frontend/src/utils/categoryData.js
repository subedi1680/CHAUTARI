  // Generate select options for dropdown menus
  export const getCategoryOptions = () => {
    const options = []
  
    // Add main categories
    categoryStructure.forEach((category) => {
      options.push({ value: category.name, label: category.name })
    })
  
    // Add subcategories
    categoryStructure.forEach((category) => {
      category.similar.forEach((subCategory) => {
        options.push({ value: subCategory, label: subCategory })
      })
    })
  
    return options
  }
  
  // Get all categories as a flat array
  export const getAllCategories = () => {
    const allCategories = []
  
    categoryStructure.forEach((category) => {
      allCategories.push(category.name)
      category.similar.forEach((subCategory) => {
        allCategories.push(subCategory)
      })
    })
  
    return allCategories
  }
  
  // Get subcategories for a specific main category
  export const getSubcategories = (mainCategory) => {
    const category = categoryStructure.find((cat) => cat.name === mainCategory)
    return category ? category.similar : []
  }
  